package com.virajgiri.triptrack.util

import android.content.Context
import android.graphics.Paint
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import androidx.core.content.FileProvider
import com.virajgiri.triptrack.data.local.BillEntity
import org.json.JSONArray
import java.io.File
import java.io.FileOutputStream
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

object InvoicePdfExporter {
    fun createPdf(context: Context, bill: BillEntity): File {
        val directory = File(context.cacheDir, "invoices").apply { mkdirs() }
        val output = File(directory, "TripTrack-Invoice-${bill.id}.pdf")
        val document = PdfDocument()
        val pageInfo = PdfDocument.PageInfo.Builder(595, 842, 1).create()
        val page = document.startPage(pageInfo)
        val canvas = page.canvas
        val titlePaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            textSize = 24f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        }
        val headingPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            textSize = 14f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        }
        val bodyPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply { textSize = 12f }
        val linePaint = Paint(Paint.ANTI_ALIAS_FLAG).apply { strokeWidth = 1f }

        var y = 54f
        canvas.drawText("TripTrack Invoice", 40f, y, titlePaint)
        y += 28f
        canvas.drawText("Invoice ID: ${bill.id}", 40f, y, bodyPaint); y += 20f
        canvas.drawText("Client: ${bill.clientNameSnapshot}", 40f, y, bodyPaint); y += 18f
        canvas.drawText("Trip date: ${bill.tripDateSnapshot}", 40f, y, bodyPaint); y += 18f
        canvas.drawText("Package: ${bill.packageTypeSnapshot}", 40f, y, bodyPaint); y += 18f
        canvas.drawText("Vehicle: ${bill.vehicleNumberSnapshot.ifBlank { "Not provided" }}", 40f, y, bodyPaint); y += 18f
        canvas.drawText("Distance: %.2f KM".format(bill.distanceKmSnapshot), 40f, y, bodyPaint); y += 18f
        canvas.drawText("Duty: ${bill.durationMinutesSnapshot / 60}h ${bill.durationMinutesSnapshot % 60}m", 40f, y, bodyPaint)
        y += 28f
        canvas.drawLine(40f, y, 555f, y, linePaint); y += 22f
        canvas.drawText("Description", 40f, y, headingPaint)
        canvas.drawText("Amount (INR)", 430f, y, headingPaint)
        y += 16f
        canvas.drawLine(40f, y, 555f, y, linePaint); y += 20f

        val items = JSONArray(bill.lineItemsJson)
        for (index in 0 until items.length()) {
            val item = items.getJSONObject(index)
            val label = item.optString("label")
            val amount = item.optLong("amountPaise")
            canvas.drawText(label.take(52), 40f, y, bodyPaint)
            canvas.drawText("%.2f".format(amount / 100.0), 455f, y, bodyPaint)
            y += 22f
            if (y > 750f) break
        }
        y += 8f
        canvas.drawLine(40f, y, 555f, y, linePaint); y += 26f
        canvas.drawText("TOTAL", 40f, y, headingPaint)
        canvas.drawText("₹%.2f".format(bill.totalPaise / 100.0), 430f, y, headingPaint)
        y += 36f
        canvas.drawText("Generated: ${SimpleDateFormat("yyyy-MM-dd HH:mm", Locale.ROOT).format(Date(bill.createdAtEpochMillis))}", 40f, y, bodyPaint)
        canvas.drawText("Generated by TripTrack", 40f, 805f, bodyPaint)

        document.finishPage(page)
        FileOutputStream(output).use { document.writeTo(it) }
        document.close()
        return output
    }

    fun shareIntent(context: Context, file: File) = android.content.Intent(android.content.Intent.ACTION_SEND).apply {
        type = "application/pdf"
        putExtra(android.content.Intent.EXTRA_STREAM, FileProvider.getUriForFile(context, "${context.packageName}.fileprovider", file))
        addFlags(android.content.Intent.FLAG_GRANT_READ_URI_PERMISSION)
    }
}
